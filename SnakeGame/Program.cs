byte[] tempMemory = new byte[0xffff];

for (int i = 0; i < gameCode.Length; i++)
{
    tempMemory[i + 0x0600] = gameCode[i];
}

var memory = NesMemory.FromBytesArray(tempMemory);
memory.WriteLittleEndian(0xFFFC, 0x0600);

var cpu = new CPU(memory);

int screenSize = 320;
int multiplier = 10;

Raylib.InitWindow(screenSize, screenSize, "Snake Game - CPU 6502");
byte[] screenState = new byte[32 * 32];

var rand = new Random();

cpu.LoadAndInterpret((cpuState) =>
{
    // A. Se o jogador fechar a janela no 'X'
    if (Raylib.WindowShouldClose())
    {
        Raylib.CloseWindow();
        Environment.Exit(0);
    }

    // B. Ler Teclado
    if (Raylib.IsKeyDown(KeyboardKey.Up)) memory.Write(0xFF, 0x77);
    if (Raylib.IsKeyDown(KeyboardKey.Left)) memory.Write(0xFF, 0x61);
    if (Raylib.IsKeyDown(KeyboardKey.Down)) memory.Write(0xFF, 0x73);
    if (Raylib.IsKeyDown(KeyboardKey.Right)) memory.Write(0xFF, 0x64);
    if (Raylib.IsKeyDown(KeyboardKey.Escape))
    {
        Raylib.CloseWindow();
        Environment.Exit(0);
    }

    // C. Gerar Maçã
    memory.Write(0xFE, (byte)rand.Next(1, 16));

    // D. Verificar se a tela mudou
    bool screenChanged = false;
    for (int i = 0; i < 1024; i++)
    {
        byte memoryColor = memory.Read((ushort)(0x0200 + i));
        if (memoryColor != screenState[i])
        {
            screenState[i] = memoryColor;
            screenChanged = true;
        }
    }

    // E. Renderizar com o Raylib
    if (screenChanged)
    {
        Raylib.BeginDrawing();

        for (int i = 0; i < 1024; i++)
        {
            Color pixelColor = GetRaylibColor(screenState[i]);

            int x = (i % 32) * multiplier;
            int y = (i / 32) * multiplier;

            // Desenha um quadrado de 10x10 na posição correta
            Raylib.DrawRectangle(x, y, multiplier, multiplier, pixelColor);
        }

        Raylib.EndDrawing();

        // Pausa para a CPU não voar rápido demais
        Thread.Sleep(70);
    }
});

