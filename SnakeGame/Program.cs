static Color GetRaylibColor(byte colorCode)
{
    return colorCode switch
    {
        0 => Color.Black,
        1 => Color.White,
        2 or 9 => Color.Gray,
        3 or 10 => Color.Red,
        4 or 11 => Color.Green,
        5 or 12 => Color.Blue,
        6 or 13 => Color.Magenta,
        7 or 14 => Color.Yellow,
        _ => Color.DarkPurple
    };
}


